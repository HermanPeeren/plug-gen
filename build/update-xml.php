<?php

/**
 * Writes the files that repeat the version, from the manifest.
 *
 * The update server is a static file in this repository, served by
 * raw.githubusercontent.com and read by Joomla's updater. Everything in it is
 * already stated in src/pluggen.xml or follows from the version, so it is
 * generated rather than edited: a hand-maintained copy of the version number is
 * exactly the kind of thing that is wrong six months later, and a wrong one
 * offers users an update that does not exist.
 *
 * The same goes for the version in the media asset manifest, which Joomla uses
 * to bust caches: one more copy of a number that is already written down.
 *
 * Run it after bumping the version; the release workflow fails if either file
 * on disk is not what this script would write.
 */

declare(strict_types=1);

$root     = \dirname(__DIR__);
$manifest = $root . '/src/pluggen.xml';

libxml_use_internal_errors(true);
$xml = simplexml_load_file($manifest);

if ($xml === false) {
    fwrite(STDERR, "The manifest is not well-formed XML.\n");
    exit(1);
}

$version = trim((string) $xml->version);

if (!preg_match('/^\d+\.\d+\.\d+(-[A-Za-z0-9.]+)?$/', $version)) {
    fwrite(STDERR, \sprintf("The manifest version \"%s\" is not of the form 1.2.3.\n", $version));
    exit(1);
}

$repo = 'https://github.com/HermanPeeren/plug-gen';

// The tag the release workflow creates, and the asset name build.php produces.
$download = \sprintf('%s/releases/download/v%s/com_pluggen-%s.zip', $repo, $version, $version);

// The checksum Joomla checks the download against; without one it warns that
// the integrity of the file cannot be validated. Only the release workflow can
// know it: the archive is built there, and one built on another machine differs
// in timestamps and line endings even when its contents do not. So the workflow
// runs this with --checksum after the build and commits the result. Without the
// flag the committed checksum is kept for as long as it describes the same
// download, so regenerating stays a no-op between releases, and dropped when
// the version moves on, because it belongs to the previous archive.
$sha512 = null;

if (\in_array('--checksum', $argv, true)) {
    $archive = $root . '/build/' . basename($download);

    if (!is_file($archive)) {
        fwrite(STDERR, "--checksum hashes the built archive, and there is none at {$archive}.\n");
        exit(1);
    }

    $sha512 = hash_file('sha512', $archive);
} elseif (is_file($root . '/updates.xml')) {
    $committed = simplexml_load_file($root . '/updates.xml');

    if ($committed !== false && trim((string) $committed->update->downloads->downloadurl) === $download) {
        $sha512 = trim((string) $committed->update->sha512) ?: null;
    }
}

$checksum = $sha512 === null ? '' : "\t\t<sha512>{$sha512}</sha512>\n";

$out = <<<XML
<?xml version="1.0" encoding="utf-8"?>
<!--
	The update server for Plug-gen, pointed at by <updateservers> in the
	component manifest. Generated by build/update-xml.php - edit the manifest,
	not this file.

	targetplatform is a regular expression anchored at the start of the Joomla
	version, so 6\.[0-9]+ offers this update on any Joomla 6 release and on none
	before it. Plug-gen is written against Joomla 6 and is not tested on 5.
-->
<updates>
	<update>
		<name>Plug-gen</name>
		<description>Generates Joomla plugins from a saved model.</description>
		<element>com_pluggen</element>
		<type>component</type>
		<version>$version</version>
		<infourl title="Plug-gen">$repo</infourl>
		<downloads>
			<downloadurl type="full" format="zip">$download</downloadurl>
		</downloads>
{$checksum}		<tags>
			<tag>stable</tag>
		</tags>
		<maintainer>Herman Peeren</maintainer>
		<maintainerurl>https://yepr.nl</maintainerurl>
		<targetplatform name="joomla" version="6\.[0-9]+"/>
		<php_minimum>8.3</php_minimum>
	</update>
</updates>

XML;

file_put_contents($root . '/updates.xml', $out);

printf(
    "updates.xml: %s -> %s, %s\n",
    $version,
    $download,
    $sha512 === null ? 'without a checksum' : 'with its checksum'
);

// The other copy of the number, which this file has claimed to write since
// it was written and did not. Joomla appends it to every asset URL to bust
// caches, so a stale one serves the previous release's stylesheet to
// everybody who already had the component - the one upgrade problem that
// looks like nothing is wrong at all. It sat at 0.4.4 while 4.1 was being
// prepared, and the release workflow would not have caught it either: it
// regenerates and diffs, and this script wrote nothing to diff.
$assets = $root . '/src/media/com_pluggen/joomla.asset.json';

if (!is_file($assets)) {
    fwrite(STDERR, "No asset manifest at {$assets}.\n");
    exit(1);
}

$json = json_decode((string) file_get_contents($assets), true);

if (!\is_array($json) || !isset($json['version'])) {
    fwrite(STDERR, "The asset manifest has no version to update.\n");
    exit(1);
}

$was = (string) $json['version'];

if ($was !== $version) {
    // Rewritten in place rather than re-encoded: json_encode would reformat
    // the whole file, and a generated diff nobody can read is a generated
    // diff nobody checks.
    file_put_contents(
        $assets,
        (string) preg_replace(
            '/("version"\s*:\s*")' . preg_quote($was, '/') . '(")/',
            '${1}' . $version . '${2}',
            (string) file_get_contents($assets),
            1
        )
    );
}

printf("joomla.asset.json: %s -> %s\n", $was, $version);
